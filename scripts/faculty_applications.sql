CREATE TABLE IF NOT EXISTS faculty_applications (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 submission_key CHAR(64) NOT NULL,
 full_name VARCHAR(160) NOT NULL,
 email VARCHAR(254) NOT NULL,
 phone VARCHAR(30) NOT NULL,
 specialty VARCHAR(200) NOT NULL,
 qualification VARCHAR(100) NOT NULL,
 workplace VARCHAR(255) DEFAULT NULL,
 experience_years TINYINT UNSIGNED DEFAULT NULL,
 portfolio_url VARCHAR(500) DEFAULT NULL,
 introduction TEXT NOT NULL,
 attachment_files MEDIUMTEXT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'new',
 admin_note TEXT DEFAULT NULL,
 reviewed_by INT DEFAULT NULL,
 reviewed_at INT DEFAULT NULL,
 notification_status VARCHAR(20) NOT NULL DEFAULT 'pending',
 notification_attempts INT UNSIGNED NOT NULL DEFAULT 0,
 notification_attempted_at INT DEFAULT NULL,
 notified_at INT DEFAULT NULL,
 ip_hash CHAR(64) NOT NULL,
 created INT NOT NULL,
 updated INT NOT NULL,
 PRIMARY KEY (id),
 UNIQUE KEY submission_key (submission_key),
 KEY status_id (status,id),
 KEY ip_created (ip_hash,created)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
